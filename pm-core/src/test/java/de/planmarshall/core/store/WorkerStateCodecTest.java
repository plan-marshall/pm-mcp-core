/**
 * The worker block of a job record (PM-WORK-2, PM-WORK-3, PM-IMPL-2): every field and every value of the closed
 * enumerations round-trips byte for byte through the canonical writer, and every document outside the one shape of the
 * block is refused at its pointer. The combination rules of the state — a task without its lease, a state before the
 * first call, a terminal state without its end reason, the start-failure pair — are refused at construction. The member
 * names, the enumeration wire names, the job id kinds and the generation shared with {@link JobRecordStoreTest} are
 * contracts; the role, the harness, its version, the model, the efforts, the digests, the plan, the task ids, the
 * worktree mark, the skill, the counts, the error texts and the instants are generated within the grammar of the block.
 */
@EnableGeneratorController
@DisplayName("Worker state codec")
class WorkerStateCodecTest {

    /** The generation of the fixtures; the contract {@link JobRecordStoreTest} names its worker record by. */
    static final JobId GENERATION = new JobId("l-00000000000000ff");
    static final Instant CONNECTED_AT = Instant.ofEpochSecond(Generators.longs(0, 4_000_000_000L).next());

    // Fixture path: the file a refusal names.
    private static final Path FILE = Path.of("/pm-base/projects/sample-project/jobs/l-00000000000000ff.json");
    private static final String DIGEST = hex(32);
    private static final String ROLE = lower();
    private static final String HARNESS = lower();
    private static final String HARNESS_VERSION = Generators.integers(0, 9).next() + "."
            + Generators.integers(0, 99).next() + "." + Generators.integers(0, 99).next();
    private static final String MODEL = lower() + "-" + lower();
    private static final String PLAN_ID = "plan-" + lower();
    private static final String EFFORT = lower();
    private static final String EFFORT_NARROWED_FROM = EFFORT + "x";
    private static final List<String> SERVED_TASKS = List.of(taskId(), taskId());
    private static final String LEASED_TASK = taskId();
    private static final String HEAD = hex(20);
    private static final String CHANGED_PATH = "src/" + lower() + "/" + lower() + ".java";
    private static final String SKILL_URI = "skill://pm/" + lower() + ":" + lower();
    private static final long IDLE_WAKEUPS = Generators.integers(1, 10).next();
    private static final long CONTEXT_TOKENS = Generators.longs(0, 200_000).next();
    private static final String HARNESS_ERROR = text(3);

    private static String lower() {
        return Generators.letterStrings(3, 12).next().toLowerCase(Locale.ROOT);
    }

    /** @return the given number of generated bytes as lower-case hex digits */
    private static String hex(int bytes) {
        var value = new byte[bytes];
        for (var index = 0; index < value.length; index++) {
            value[index] = Generators.integers(0, 255).next().byteValue();
        }
        return HexFormat.of().formatHex(value);
    }

    /** @return a queue task id of the grammar of the block, {@code qt-} and 16 hex digits */
    private static String taskId() {
        return "qt-" + hex(8);
    }

    /** The builder of a worker that connected and waits for its first offer, every optional member absent. */
    static WorkerStateBuilder base() {
        return WorkerState.builder().role(ROLE).configurationDigest(DIGEST).roleClass(RoleClass.WRITER)
                .form(Form.FRESH).harness(HARNESS).harnessVersion(HARNESS_VERSION).model(MODEL)
                .generationId(GENERATION).workdir(new Workdir(Workdir.Kind.PLAN_WORKTREE, PLAN_ID))
                .promptDigest(DIGEST).jobTokenSha256(DIGEST).connectedAt(CONNECTED_AT).state(State.WAITING)
                .stateAt(CONNECTED_AT.plusSeconds(1)).servedTasks(List.of()).idleWakeups(0)
                .contextTokens(ContextTokens.NOT_MEASURED).deliveredSkills(List.of()).startFailure(false);
    }

    /** The worker that connected and waits for its first offer. */
    static WorkerState waiting() {
        return base().build();
    }

    /** The worker with every optional member present, at its terminal state. */
    static WorkerState full() {
        return base().effort(EFFORT).effortNarrowedFrom(EFFORT_NARROWED_FROM).state(State.ENDED)
                .stateAt(CONNECTED_AT.plusSeconds(30))
                .servedTasks(SERVED_TASKS)
                .worktreeMark(new WorktreeMark(HEAD, List.of(CHANGED_PATH), CONNECTED_AT.plusSeconds(20)))
                .idleWakeups(IDLE_WAKEUPS).contextTokens(ContextTokens.measured(CONTEXT_TOKENS))
                .endReason(EndReason.TASK_DONE)
                .deliveredSkills(List.of(new DeliveredSkill(SKILL_URI, DIGEST, CONNECTED_AT.plusSeconds(2))))
                .build();
    }

    /** A worker that exited before its first call. */
    static WorkerState startFailed() {
        return base().connectedAt(null).jobTokenSha256(null).state(State.ENDED)
                .stateAt(CONNECTED_AT.plusSeconds(30)).endReason(EndReason.START_FAILURE).startFailure(true)
                .harnessError(HARNESS_ERROR).build();
    }

    /** One state per value of every closed enumeration, so the round trip covers each of them. */
    static List<Arguments> variants() {
        var variants = new ArrayList<Arguments>();
        variants.add(Arguments.of("waiting", waiting()));
        variants.add(Arguments.of("full", full()));
        variants.add(Arguments.of("start failure", startFailed()));
        for (var state : State.values()) {
            variants.add(Arguments.of("state " + state.wireName(), inState(state)));
        }
        for (var reason : EndReason.values()) {
            variants.add(Arguments.of("end reason " + reason.wireName(), inEndReason(reason)));
        }
        for (var roleClass : RoleClass.values()) {
            variants.add(Arguments.of("class " + roleClass.wireName(), inClass(roleClass)));
        }
        for (var form : Form.values()) {
            variants.add(Arguments.of("form " + form.wireName(), base().form(form).build()));
        }
        for (var kind : Workdir.Kind.values()) {
            variants.add(Arguments.of("workdir " + kind.wireName(), base()
                    .workdir(new Workdir(kind, kind == Workdir.Kind.PLAN_WORKTREE ? PLAN_ID : null)).build()));
        }
        return variants;
    }

    private static WorkerState inState(State state) {
        var builder = base().state(state).stateAt(CONNECTED_AT.plusSeconds(2));
        if (state.isTerminal()) {
            builder.endReason(state == State.LOST ? EndReason.SILENCE : EndReason.TASK_DONE);
        } else if (state != State.WAITING) {
            builder.task(LEASED_TASK);
        }
        return builder.build();
    }

    private static WorkerState inEndReason(EndReason reason) {
        var builder = base().state(State.ENDED).stateAt(CONNECTED_AT.plusSeconds(30)).endReason(reason);
        if (reason == EndReason.START_FAILURE) {
            builder.connectedAt(null).jobTokenSha256(null).startFailure(true).harnessError(HARNESS_ERROR);
        }
        return builder.build();
    }

    private static WorkerState inClass(RoleClass roleClass) {
        var builder = base().roleClass(roleClass);
        if (roleClass == RoleClass.ZERO_TOOL) {
            builder.jobTokenSha256(null);
        }
        return builder.build();
    }

    private static String replace(String document, String fragment, String replacement) {
        assertTrue(document.contains(fragment), "the fixture should contain the fragment");
        return document.replace(fragment, replacement);
    }

    private static StoreRefusal refusalOf(String document) {
        return assertThrows(StoreRefusal.class, () -> WorkerStateCodec.read(FILE, document),
                "the document should be refused by the reader");
    }

    @Nested
    @DisplayName("round trip")
    class RoundTrip {

        @ParameterizedTest(name = "{0}")
        @MethodSource("de.planmarshall.core.store.WorkerStateCodecTest#variants")
        @DisplayName("a worker state is read back equal and written again byte for byte")
        void roundTrip(String name, WorkerState state) {
            var text = WorkerStateCodec.write(state);

            var read = WorkerStateCodec.read(FILE, text);

            assertAll(
                    () -> assertEquals(state, read, "the worker state should be read back equal"),
                    () -> assertEquals(text, WorkerStateCodec.write(read),
                            "the state should be written again byte for byte"));
        }

        @Test
        @DisplayName("the members are written through the canonical writer, sorted by their names")
        void canonicalOrder() {
            var text = WorkerStateCodec.write(full());
            var positions = WorkerStateCodec.MEMBERS.stream().sorted()
                    .map(member -> text.indexOf("\"" + member + "\":")).toList();

            assertAll(
                    () -> assertTrue(positions.stream().allMatch(position -> position >= 0),
                            "every member should be written"),
                    () -> assertEquals(positions.stream().sorted().toList(), positions,
                            "the members should be sorted by their names"),
                    () -> assertTrue(text.startsWith("{") && text.endsWith("}"),
                            "the block should be one JSON object"),
                    () -> assertTrue(!text.contains("\n") && !text.contains(": "),
                            "the block should be written without spacing"));
        }

        @Test
        @DisplayName("the optional effort_narrowed_from may be omitted, every other member may not (member name)")
        void optionalMember() {
            var document = replace(WorkerStateCodec.write(waiting()), ",\"effort_narrowed_from\":null", "");

            var read = WorkerStateCodec.read(FILE, document);

            assertAll(
                    () -> assertNull(read.effortNarrowedFrom(), "the omitted member should read as absent"),
                    () -> assertEquals(waiting(), read, "the omitted member should read the same"));
        }
    }

    @Nested
    @DisplayName("refusals")
    class Refusals {

        @Test
        @DisplayName("an unknown member is refused at its pointer")
        void unknownMember() {
            var refusal = refusalOf(replace(WorkerStateCodec.write(waiting()), "\"role\":", "\"extra\":1,\"role\":"));

            assertAll(
                    () -> assertEquals(Outcome.UNREADABLE, refusal.outcome(), "the refusal should be unreadable"),
                    () -> assertEquals(FILE, refusal.file(), "the refusal should name the file read"),
                    () -> assertTrue(refusal.getMessage().contains("'extra'"),
                            "the refusal should name the unknown member"));
        }

        @Test
        @DisplayName("a missing required member is refused at its pointer")
        void missingMember() {
            var refusal = refusalOf(replace(WorkerStateCodec.write(waiting()), ",\"harness_error\":null", ""));

            assertTrue(refusal.getMessage().contains("'harness_error'"),
                    "the refusal should name the missing member");
        }

        @Test
        @DisplayName("a member twice is refused")
        void memberTwice() {
            var role = "\"role\":" + json(ROLE) + ",";
            var refusal = refusalOf(replace(WorkerStateCodec.write(waiting()), role, role + role));

            assertTrue(refusal.getMessage().contains("'role' twice"), "the refusal should name the repeated member");
        }

        @Test
        @DisplayName("an undeclared value of a closed enumeration is refused at its pointer (wire names)")
        void undeclaredValue() {
            var refusal = refusalOf(replace(WorkerStateCodec.write(waiting()), "\"class\":\"writer\"",
                    "\"class\":\"owner\""));

            assertTrue(refusal.getMessage().contains("'class'"), "the refusal should name the class member");
        }

        @Test
        @DisplayName("a negative context size is refused at its pointer")
        void negativeContext() {
            var refusal = refusalOf(replace(WorkerStateCodec.write(waiting()), "\"context_tokens\":\"unmeasured\"",
                    "\"context_tokens\":-" + Generators.integers(1, 1_000).next()));

            assertTrue(refusal.getMessage().contains("context_tokens"),
                    "the refusal should name the context size");
        }

        @Test
        @DisplayName("a working directory of another kind with a plan id is refused (kind wire names)")
        void workdirWithPlanId() {
            var refusal = refusalOf(replace(WorkerStateCodec.write(waiting()), "\"kind\":\"plan_worktree\"",
                    "\"kind\":\"project_checkout\""));

            assertTrue(refusal.getMessage().contains("project_checkout"),
                    "the refusal should name the workdir kind");
        }

        @Test
        @DisplayName("a generation that is not a worker's job id is refused (job id kinds are the contract)")
        void generationOfAnotherKind() {
            var refusal = refusalOf(replace(WorkerStateCodec.write(waiting()),
                    "\"generation_id\":\"l-00000000000000ff\"", "\"generation_id\":\"x-00000000000000ff\""));

            var foreignGeneration = base().generationId(new JobId("b-00000000000000ff"));

            assertAll(
                    () -> assertThrows(IllegalArgumentException.class, foreignGeneration::build,
                            "a build job id should be no generation"),
                    () -> assertTrue(refusal.getMessage().contains("generation_id"),
                            "the refusal should name the generation"));
        }
    }

    @Nested
    @DisplayName("combination rules")
    class Combinations {

        @Test
        @DisplayName("a terminal state without an end reason, and an end reason before the end, are refused")
        void terminalState() {
            var terminalWithoutReason = base().state(State.ENDED);
            var reasonBeforeEnd = base().state(State.WAITING).endReason(EndReason.TASK_DONE);

            assertAll(
                    () -> assertTrue(assertThrows(IllegalArgumentException.class, terminalWithoutReason::build,
                            "a terminal state without reason is refused").getMessage().contains("end_reason"),
                            "a terminal state needs its end reason"),
                    () -> assertTrue(assertThrows(IllegalArgumentException.class, reasonBeforeEnd::build,
                            "a waiting state with a reason is refused").getMessage().contains("end_reason"),
                            "an end reason before the end is refused"));
        }

        @Test
        @DisplayName("a task in a state that holds none is refused")
        void taskWithoutLease() {
            var stateWithoutLease = base().task(LEASED_TASK);

            var failure = assertThrows(IllegalArgumentException.class, stateWithoutLease::build,
                    "a task in the waiting state is refused");

            assertTrue(failure.getMessage().contains("leased"), "the refusal should name the leased states");
        }

        @Test
        @DisplayName("a state timestamp before the first call is refused")
        void beforeConnection() {
            var stateBeforeConnection = base().stateAt(CONNECTED_AT.minusSeconds(1));

            var failure = assertThrows(IllegalArgumentException.class, stateBeforeConnection::build,
                    "a state before the first call is refused");

            assertTrue(failure.getMessage().contains("state_at"), "the refusal should name the state instant");
        }

        @Test
        @DisplayName("the start failure and its error text are one pair")
        void startFailurePair() {
            var errorWithoutFailure = base().harnessError(HARNESS_ERROR);
            var failureWithoutError = base().state(State.ENDED).endReason(EndReason.START_FAILURE)
                    .startFailure(true);

            assertAll(
                    () -> assertTrue(assertThrows(IllegalArgumentException.class, errorWithoutFailure::build,
                            "an error text without failure is refused").getMessage().contains("harness_error"),
                            "an error without a failure is refused"),
                    () -> assertTrue(assertThrows(IllegalArgumentException.class, failureWithoutError::build,
                            "a connected start failure is refused").getMessage().contains("first call"),
                            "the refusal should name the first call"));
        }

        @Test
        @DisplayName("a narrowed-from effort without the narrowed effort is refused")
        void narrowWithoutEffort() {
            var narrowedWithoutEffort = base().effortNarrowedFrom(EFFORT_NARROWED_FROM);

            assertThrows(IllegalArgumentException.class, narrowedWithoutEffort::build,
                    "a narrowed-from without an effort is refused");
        }

        @Test
        @DisplayName("a zero-tool worker holds no job token")
        void zeroToolToken() {
            var zeroToolWithoutToken = base().roleClass(RoleClass.ZERO_TOOL);

            assertThrows(IllegalArgumentException.class, zeroToolWithoutToken::build,
                    "a zero-tool worker with a token is refused");
        }
    }
}
