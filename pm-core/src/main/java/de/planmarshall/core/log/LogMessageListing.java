package de.planmarshall.core.log;

import de.cuioss.tools.logging.LogRecord;
import java.lang.reflect.Field;
import java.lang.reflect.Modifier;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Comparator;
import java.util.List;
import lombok.experimental.UtilityClass;

/**
 * Renders the generated listing of a log-message holder: the identifier and the template of every INFO, WARN and ERROR
 * record, one AsciiDoc table per level, for {@code doc/LogMessages.adoc} to include and for a byte check to compare
 * with the committed file.
 * <p>
 * The holder is the source of the listing: the records are read from its three level classes and sorted by identifier,
 * so the listing states no value the code does not hold. A committed listing that no longer equals a fresh rendering is
 * the defect the byte check of each module's holder test reports.
 *
 * @since 0.1
 */
@UtilityClass
public class LogMessageListing {

    /** The notice a generated listing starts with. */
    private static final String GENERATED = "// Generated by de.planmarshall.core.log.LogMessageListing; do not edit.";

    /** The level classes of a holder, in the order the listing states them. */
    private static final List<String> LEVELS = List.of("INFO", "WARN", "ERROR");

    /** The table form of one level, two columns: the identifier and the template. */
    private static final String TABLE_HEADER = "[cols=\"1,4\", options=\"header\"]";

    /**
     * Renders the listing of a holder from the holder itself.
     *
     * @param holder the log-message holder whose {@code INFO}, {@code WARN} and {@code ERROR} classes carry the records
     * @return the AsciiDoc listing, one table per level
     */
    public static String render(Class<?> holder) {
        var sections = new ArrayList<String>();
        for (String level : LEVELS) {
            sections.add(section(holder, level));
        }
        return GENERATED + "\n\n" + String.join("\n\n", sections) + "\n";
    }

    /**
     * Compares a fresh rendering with a committed listing byte for byte, without parsing either.
     *
     * @param expected the bytes of a fresh rendering
     * @param actual   the bytes of the committed listing
     * @return whether the committed listing is the current rendering
     */
    public static boolean same(byte[] expected, byte[] actual) {
        return Arrays.equals(expected, actual);
    }

    private static String section(Class<?> holder, String level) {
        var table = new StringBuilder();
        table.append(TABLE_HEADER).append('\n');
        table.append("|===\n");
        table.append("|ID |Message\n");
        for (LogRecord record : records(holder, level)) {
            table.append('|').append(record.resolveIdentifierString()).append(" |")
                    .append(record.getTemplate().replace("|", "\\|")).append('\n');
        }
        table.append("|===");
        return "=== " + level + " Level (" + range(level) + ")\n\n" + table;
    }

    private static String range(String level) {
        return switch (level) {
            case "INFO" -> "001-099";
            case "WARN" -> "100-199";
            default -> "200-299";
        };
    }

    private static List<LogRecord> records(Class<?> holder, String level) {
        var nested = Arrays.stream(holder.getDeclaredClasses())
                .filter(candidate -> level.equals(candidate.getSimpleName()))
                .findFirst()
                .orElseThrow(() -> new IllegalStateException("holder has no " + level + " class: " + holder.getName()));
        var records = new ArrayList<LogRecord>();
        for (Field field : nested.getDeclaredFields()) {
            if (Modifier.isStatic(field.getModifiers()) && LogRecord.class.isAssignableFrom(field.getType())) {
                records.add(read(field));
            }
        }
        records.sort(Comparator.comparingInt(LogRecord::getIdentifier));
        return records;
    }

    private static LogRecord read(Field field) {
        try {
            return (LogRecord) field.get(null);
        } catch (IllegalAccessException e) {
            throw new IllegalStateException("cannot read " + field, e);
        }
    }
}
